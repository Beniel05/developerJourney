// Operators

// 1. Addition
console.log(19 + 3); // 22
console.log(19 + 3.1); // 22.1

// 2. Subtraction
console.log(10 - 5); // 5
console.log('10' - 5); // 5 = Even with one string and one number

// 3. Multiplication
console.log(10 * 5); // 50 
console.log(10 * 5.6); // 56

// 4. Division
console.log(10 / 4); // 2.5 not 2 floored Quotient
console.log(-11 / 2); // -5.5 = Quotient

// 5. Modulo / Modulus
console.log(11 % 2); // 1 = Remainder

// 6. Exponential
console.log(10 ** 2); // 10 ^ 2 < = > 10 x 10 < = > 100
