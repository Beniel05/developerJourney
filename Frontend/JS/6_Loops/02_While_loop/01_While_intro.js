// Printing 1 to 10 using while loop.

let i = 1; // declaration
while (i <= 10) { // condition
    console.log(i);
    i++; // increment
}

// Print a countdown from 5 down to 1. Stop the loop when the counter hits 0.
let counter = 5;
while (counter > 0) {
  console.log(counter);  
  counter--; // This subtracts 1 each time so the loop eventually stops!
}
